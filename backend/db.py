from contextlib import asynccontextmanager as _acm


@_acm
async def txn(db: AsyncSession):
    """Drop-in for `async with db.begin():` — works whether or not the
    session already has an implicit transaction from earlier SELECTs."""
    if not db.in_transaction():
        async with db.begin():
            yield
    else:
        try:
            yield
            await db.commit()
        except Exception:
            await db.rollback()
            raise
